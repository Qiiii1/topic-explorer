export function demoGenerate(input) {
  if (input.operation === 'merge') {
    const [a,b] = input.nodes;
    const titles = a.title + b.title;
    const match = /独居/.test(titles) && /新居民|新搬|新环境/.test(titles);
    return { mode:'demo', nodes:[{ title: match ? '独居的新居民' : `${a.title.slice(0,12)}与${b.title.slice(0,12)}的交集`, description: match ? '刚搬入社区、独自生活，还没有形成稳定邻里联系的人。' : `把“${a.title}”与“${b.title}”共同成立的条件作为一个待验证的候选方向。`, rationale: match ? '同时保留“独自生活”和“新近迁入”两个条件，缩小人群范围；原来的两张卡片仍然保留。' : `保留两个来源，探索它们是否存在能够同时成立的共同条件。此处为示例结果，需要进一步确认交集是否合理。` }] };
  }
  const node=input.node, kind=input.targetKind, count=[3,6,10].includes(input.count)?input.count:3;
  const topic=[input.project?.description,node.title,...(input.ancestors||[]).map(n=>n.title)].join(' ');
  const source=node.kind===kind?refinements[kind]:(/城市|社区|公共空间|通勤|居民|人与/.test(topic)?city[kind]:generic[kind]);
  const excluded=new Set(input.exclude||[]); const candidates=source.filter(([title])=>!excluded.has(title));
  const result=[];
  for(let i=0;i<count;i++){
    const [base,description]=candidates[i % Math.max(candidates.length,1)] || source[i%source.length];
    const title=excluded.has(base)||i>=candidates.length?`${base} · 另一种切入`:base;
    result.push({title,description,rationale: node.kind==='root'?`从“${node.title.slice(0,30)}”出发，先通过一个具体${kind==='scene'?'生活情境':kind==='pain'?'待验证的困难':'观察对象'}找到切入口。`:`沿着“${node.title}”继续探索，把上层想法细化为${kind==='scene'?'可观察的情境':kind==='pain'?'需要验证的问题':'更明确的观察对象'}。`});
  }
  return {mode:'demo',nodes:result};
}
